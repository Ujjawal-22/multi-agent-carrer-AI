"""
Structured output for the Matching Agent.

IMPORTANT ASYMMETRY, worth understanding clearly:
- MatchingResult and SubScoreBreakdown are NEVER passed to Gemini as a
  response_schema — they are always fully constructed by our own
  deterministic Python code (matching_scorer.py), so normal Pydantic
  defaults are safe here and impose no Gemini constraint.
- MatchNarrative IS passed to Gemini as response_schema (it's the one
  small piece we ask the LLM to write). It has a single required field
  and no defaults, so it already complies with the no-defaults-for-Gemini
  rule established during the ATS Agent work.
"""

from pydantic import BaseModel, Field


class SubScoreBreakdown(BaseModel):
    technical_skill_match: float = 0.0
    ats_keyword_match: float = 0.0
    experience_project_match: float = 0.0
    education_match: float = 0.0
    domain_match: float = 0.0


MATCHING_METHODOLOGY_NOTE = (
    "The overall match score is a weighted combination of five sub-scores, "
    "each computed deterministically (not by an LLM) from the outputs of "
    "the Skill Gap, ATS, and Experience/Project agents: "
    "(1) technical_skill_match = matching skills count with partial "
    "matches counted as half-credit, as a percentage of all skills "
    "considered relevant; "
    "(2) ats_keyword_match = the ATS Agent's own keyword-coverage score, "
    "reused directly rather than recomputed; "
    "(3) experience_project_match = the average of each project's "
    "relevance rating (high/medium/low) from the Experience Agent; "
    "(4) education_match and (5) domain_match use a simple keyword-overlap "
    "heuristic against the job description's stated requirements/domain — "
    "these two are intentionally the weakest and lowest-weighted "
    "sub-scores, since they rely on shallow text matching rather than "
    "semantic understanding. Weights are configurable and, by default, "
    "sum to 1.0. The written narrative summary is LLM-generated but is "
    "instructed to explain these already-computed numbers, not invent new "
    "ones."
)


class MatchingResult(BaseModel):
    overall_match_score: float = 0.0
    sub_scores: SubScoreBreakdown = Field(default_factory=SubScoreBreakdown)
    weights_used: SubScoreBreakdown = Field(default_factory=SubScoreBreakdown)
    methodology_note: str = MATCHING_METHODOLOGY_NOTE
    narrative_summary: str = ""


class MatchNarrative(BaseModel):
    """The only piece of this agent's output actually generated by an LLM."""

    narrative_summary: str
